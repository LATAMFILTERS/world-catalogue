function parseRows(raw) {
  return raw.trim().split('\n').map(line => {
    const [equipment, year, type, options, engine] = line.split('|');
    const clean = v => (!v || v.trim() === '-' || v.trim() === '') ? null : v.trim();
    const e = clean(engine);
    // If engine looks like "MAKE MODEL" same as equipment, it's a self-reference — keep as-is
    return {
      equipment: equipment.trim(),
      year:      clean(year),
      type:      clean(type),
      options:   clean(options),
      engine:    e,
    };
  }).filter(r => r.equipment);
}

async function run() {
  const apps = parseRows(RAW);
  console.log(`Parsed ${apps.length} equipment entries`);

  if (DRY) {
    console.log('\nSample (first 5):');
    apps.slice(0, 5).forEach(a => console.log(JSON.stringify(a)));
    console.log('\n[DRY RUN] No DB writes. Remove --dry to execute.');
    return;
  }

  const client = new Client(DB_CONFIG);
  await client.connect();

  // Find the SKU for P550440
  const { rows } = await client.query(
    `SELECT sku, codigo_base, jsonb_array_length(COALESCE(equipment_applications,'[]'::jsonb)) AS current_equip
     FROM elimfilters_catalog WHERE codigo_base = 'P550440'`
  );

  if (!rows.length) {
    console.error('P550440 not found in DB');
    await client.end();
    return;
  }

  const { sku, current_equip } = rows[0];
  console.log(`Found: ${sku} (P550440) — currently has ${current_equip} equipment entries`);

  await client.query(
    `UPDATE elimfilters_catalog SET equipment_applications = $1::jsonb WHERE codigo_base = 'P550440'`,
    [JSON.stringify(apps)]
  );

  console.log(`✅ Updated ${sku}: ${apps.length} equipment applications written`);
  await client.end();
}

run().catch(e => { console.error('FAILED:', e.message); process.exit(1); });
