/**
 * Post-build script: appends all /knowledge-center/* routes to the sitemap.
 *
 * frontend/src/app/sitemap.ts generates the core routes on every `next build`.
 * frontend/out/sitemap.xml is the only sitemap that is ever served — Next's
 * static export always regenerates it fresh from that route.
 * This script incorporates the real Knowledge Center routes (scanned from the
 * actual frontend/out/knowledge-center/**\/index.html files that `next build`
 * produced) into that same frontend/out/sitemap.xml.
 * frontend/public/sitemap.xml is not a valid source or destination: it is
 * never read by Next and never served, so it must not be written here.
 *
 * Run automatically via package.json "postbuild" script.
 */

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'fs';
import { join, relative } from 'path';
import { fileURLToPath } from 'url';
import { dirname } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const ROOT = join(__dirname, '..');
const OUT_DIR = join(ROOT, 'frontend', 'out');
const KC_OUT_DIR = join(OUT_DIR, 'knowledge-center');
const OUT_SITEMAP = join(OUT_DIR, 'sitemap.xml');
const BASE_URL = 'https://elimfilters.com';
const TODAY = new Date().toISOString().split('T')[0];

function walkDir(dir, results = []) {
  if (!existsSync(dir)) return results;
  for (const entry of readdirSync(dir)) {
    const fullPath = join(dir, entry);
    const stat = statSync(fullPath);
    if (stat.isDirectory()) {
      walkDir(fullPath, results);
    } else if (entry === 'index.html') {
      results.push(fullPath);
    }
  }
  return results;
}

function buildUrl(indexPath) {
  const rel = relative(OUT_DIR, indexPath)
    .replace(/\\/g, '/')
    .replace(/\/index\.html$/, '');
  return `${BASE_URL}/${rel.replace(/^\/+|\/+$/g, '')}/`;
}

function priorityFor(url) {
  const depth = url.replace(BASE_URL, '').split('/').filter(Boolean).length;
  if (depth === 1) return '0.8';
  if (depth === 2) return '0.7';
  return '0.6';
}

function buildEntry(url) {
  return `  <url>
    <loc>${url}</loc>
    <lastmod>${TODAY}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>${priorityFor(url)}</priority>
  </url>`;
}

function isIndexable(htmlPath) {
  try {
    const html = readFileSync(htmlPath, 'utf8');
    return !html.includes('noindex');
  } catch {
    return true;
  }
}

function injectIntoSitemap(sitemapPath, entries) {
  if (!existsSync(sitemapPath)) {
    throw new Error(
      `${sitemapPath} does not exist. It is mandatory output of \`next build\` ` +
        '(generated by frontend/src/app/sitemap.ts) — run `next build` before this script.'
    );
  }
  const content = readFileSync(sitemapPath, 'utf8');

  if (!content.includes('</urlset>')) {
    throw new Error(`${sitemapPath} does not contain a </urlset> closing tag — refusing to write a malformed sitemap.`);
  }

  // Remove any previously injected KC block
  const withoutKcBlock = content.replace(/\n  <!-- ── Knowledge Center ── -->[\s\S]*?(?=\n<\/urlset>)/, '');

  const block = `\n  <!-- ── Knowledge Center ── -->\n${entries.join('\n')}\n`;
  const updated = withoutKcBlock.replace('</urlset>', `${block}</urlset>`);
  writeFileSync(sitemapPath, updated, 'utf8');
}

// ── Main ─────────────────────────────────────────────────────────────────────

if (!existsSync(KC_OUT_DIR)) {
  console.error('[generate-kc-sitemap] ERROR: knowledge-center out dir not found. Run `next build` first.');
  process.exit(1);
}

const indexFiles = walkDir(KC_OUT_DIR);
const urls = [];
const entries = [];
for (const htmlFile of indexFiles.sort()) {
  if (isIndexable(htmlFile)) {
    const url = buildUrl(htmlFile);
    urls.push(url);
    entries.push(buildEntry(url));
  }
}

console.log(`[generate-kc-sitemap] Found ${urls.length} knowledge-center pages`);

injectIntoSitemap(OUT_SITEMAP, entries);
console.log(`[generate-kc-sitemap] Updated: ${OUT_SITEMAP}`);

console.log(`[generate-kc-sitemap] Done — ${urls.length} KC URLs added to sitemap`);